#!/usr/bin/env node
/**
 * export_e2k_cft.mjs — Genera .e2k directamente (sin dependencia TS) del
 * benchmark CFT (columnas Concrete-Filled Tube + vigas I).
 *
 * Uso:  node export_e2k_cft.mjs <cftNoSlab|cftDeckSlab>
 *       node export_e2k_cft.mjs                 → genera ambos
 *
 * Modelo IDÉNTICO a run_matrix_cft.mjs / run_opensees_cft.py:
 *   Bay 4×4 m, story h=4 m, mesh 4×4
 *   4 columnas CFT en esquina (SHAPE General, propiedades transformadas)
 *   16 vigas perimetrales W360x60 acero
 *   Pin en base.
 *
 * cftNoSlab    → sin shell, 4×20 kN puntuales en midspan de vigas
 * cftDeckSlab  → con losa shellThin t=0.10 m, q=5 kN/m²
 *
 * Sección CFT (SHAPE "General"):
 *   HSS 250×250×10 + concreto fill 230×230, transformada a steel-equivalent:
 *     A = 1.6212e-2 m²   I22 = I33 = 1.2147e-4 m⁴   J = 1.8464e-4 m⁴
 *
 * Formato: replica EXACTAMENTE composite_slab_shellthin_frame.e2k (validado
 * con ETABS 22.6.0).
 */
import { writeFileSync, mkdirSync, existsSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));

// ── Constantes ────────────────────────────────────────────────────────────
const Lx = 4, Ly = 4;
const slabZ = 4;
const t_slab = 0.10;
const q_unif = 5;
const P_point = 20;
const nx = 4, ny = 4;
const nNx = nx + 1;
const dx = Lx / nx, dy = Ly / ny;

const E_c = 25e6, nu_c = 0.20;
const E_s = 200e6;

// W360x60
const W_h = 0.352, W_b = 0.203, W_tf = 0.013, W_tw = 0.008;

// CFT transformed properties
const D_out = 0.250, t_HSS = 0.010;
const D_in  = D_out - 2*t_HSS;
const A_steel_HSS = D_out**2 - D_in**2;
const A_conc      = D_in**2;
const I_steel_HSS = (D_out**4 - D_in**4) / 12;
const I_conc      = D_in**4 / 12;
const J_steel_HSS = 2 * I_steel_HSS;
const n_modular   = E_s / E_c;
const A_cft = A_steel_HSS + A_conc / n_modular;
const I_cft = I_steel_HSS + I_conc / n_modular;
const J_cft = J_steel_HSS;
const S_cft = I_cft / (D_out / 2);
const r_cft = Math.sqrt(I_cft / A_cft);

// ── Generador ─────────────────────────────────────────────────────────────
function generateE2k(setup) {
  const hasSlab = setup === "cftDeckSlab";
  const lines = [];

  // Header
  lines.push(`$ File generated by export_e2k_cft.mjs (CFT bench, ${setup})`);
  lines.push(``);
  lines.push(`$ PROGRAM INFORMATION`);
  lines.push(`  PROGRAM  "ETABS"  VERSION "22.6.0"`);
  lines.push(``);
  lines.push(`$ CONTROLS`);
  lines.push(`  UNITS  "KN"  "M"  "C"  `);
  lines.push(`  TITLE2  "Composite CFT cols + I-beams (${setup})"`);
  lines.push(``);

  // Stories
  lines.push(`$ STORIES - IN SEQUENCE FROM TOP`);
  lines.push(`  STORY "Level_1"  HEIGHT 4 MASTERSTORY "Yes"  `);
  lines.push(`  STORY "Base"  ELEV 0`);
  lines.push(``);

  // Grids
  lines.push(`$ GRIDS`);
  lines.push(`  GRIDSYSTEM "G1"  TYPE "CARTESIAN"  BUBBLESIZE 1`);
  for (let i = 0; i <= nx; i++) {
    const lab = String.fromCharCode("A".charCodeAt(0) + i);
    lines.push(`  GRID "G1"  LABEL "${lab}"  DIR "X"  COORD ${i * dx}  VISIBLE "Yes"  BUBBLELOC "End"`);
  }
  for (let j = 0; j <= ny; j++) {
    lines.push(`  GRID "G1"  LABEL "${j + 1}"  DIR "Y"  COORD ${j * dy}  VISIBLE "Yes"  BUBBLELOC "Start"`);
  }
  lines.push(``);

  // Diaphragm (sólo si hay slab)
  if (hasSlab) {
    lines.push(`$ DIAPHRAGM NAMES`);
    lines.push(`  DIAPHRAGM "D1"    TYPE RIGID`);
    lines.push(``);
  }

  // Materials
  lines.push(`$ MATERIAL PROPERTIES`);
  lines.push(`  MATERIAL  "Mat_1"    TYPE "Concrete"    WEIGHTPERVOLUME 2.4`);
  lines.push(`  MATERIAL  "Mat_1"    SYMTYPE "Isotropic"  E ${E_c}  U ${nu_c}  A 1E-05`);
  lines.push(`  MATERIAL  "Mat_1"    FC 25000`);
  lines.push(`  MATERIAL  "Mat_2"    TYPE "Steel"    WEIGHTPERVOLUME 7.85`);
  lines.push(`  MATERIAL  "Mat_2"    SYMTYPE "Isotropic"  E ${E_s}  U 0.3  A 1E-05`);
  lines.push(`  MATERIAL  "Mat_2"    FY 345000  FU 450000  EFFFY 379500  EFFFU 495000`);
  lines.push(``);

  // Frame Sections — vigas W360x60 (I) + columnas CFT (Filled Steel Tube nativo ETABS)
  // ETABS soporta SHAPE "Filled Steel Tube" que computa la sección compuesta
  // CFT internamente: tubo de acero + relleno de concreto, con transformación
  // automática basada en E_steel y E_fill. Esto reemplaza el approach de
  // "Steel Tube + property modifiers" porque ETABS hace la transformación correcta.
  // Referencia: family_b_stell_composite_shell_walls_rigid_modal.e2k línea 78:
  //   FRAMESECTION "FSec1" MATERIAL "A572Gr50" SHAPE "Filled Steel Tube"
  //     D 0.3 B 0.3 TF 0.012 TW 0.012 FILLMATERIAL "4000Psi"
  lines.push(`$ FRAME SECTIONS`);
  lines.push(`  FRAMESECTION  "W360X60"  MATERIAL "Mat_2"  SHAPE "Steel I/Wide Flange"  D ${W_h}  B ${W_b}  TF ${W_tf}  TW ${W_tw}`);
  // CFT compuesto nativo ETABS (steel HSS + concrete fill)
  lines.push(`  FRAMESECTION  "CFT_HSS250x10"  MATERIAL "Mat_2"  SHAPE "Filled Steel Tube"  D ${D_out}  B ${D_out}  TF ${t_HSS}  TW ${t_HSS}  FILLMATERIAL "Mat_1"  `);
  lines.push(``);

  // Slab (sólo si hay slab)
  if (hasSlab) {
    lines.push(`$ SLAB PROPERTIES`);
    lines.push(`  SHELLPROP  "Losa"  PROPTYPE  "Slab"  MATERIAL "Mat_1"  MODELINGTYPE "ShellThin"  SLABTYPE "Slab"  SLABTHICKNESS ${t_slab}`);
    lines.push(``);
  }

  // Point coordinates: 25 plan points
  lines.push(`$ POINT COORDINATES`);
  let pid = 0;
  for (let j = 0; j <= ny; j++) {
    for (let i = 0; i <= nx; i++) {
      pid++;
      lines.push(`  POINT "${pid}"  ${i * dx} ${j * dy} `);
    }
  }
  lines.push(``);

  // Line connectivities: 16 beams + 4 columns
  lines.push(`$ LINE CONNECTIVITIES`);
  let eid = 0;
  // Beams: 4 perimeter sides × nx elements
  // Bottom (y=0): pids 1..nx+1 (1,2,3,4,5)
  // Top (y=Ly): pids 21..25
  // Left (x=0): pids 1,6,11,16,21
  // Right (x=Lx): pids 5,10,15,20,25
  const beamPairs = [];
  for (let i = 0; i < nx; i++) beamPairs.push([i + 1, i + 2]);                              // bottom
  const topStart = ny * nNx;
  for (let i = 0; i < nx; i++) beamPairs.push([topStart + i + 1, topStart + i + 2]);        // top
  for (let j = 0; j < ny; j++) beamPairs.push([j * nNx + 1, (j + 1) * nNx + 1]);            // left
  for (let j = 0; j < ny; j++) beamPairs.push([j * nNx + nNx, (j + 1) * nNx + nNx]);        // right
  for (const [a, b] of beamPairs) {
    eid++;
    lines.push(`  LINE  "E${eid}"  BEAM  "${a}"  "${b}"  0`);
  }
  // Columns: 4 corners (top point = top, nStories = 1)
  const cornerPids = [1, nx + 1, ny * nNx + 1, ny * nNx + nNx];
  for (const cp of cornerPids) {
    eid++;
    lines.push(`  LINE  "E${eid}"  COLUMN  "${cp}"  "${cp}"  1`);
  }
  const lastBeamId = beamPairs.length;
  const colIds = [];
  for (let k = 0; k < 4; k++) colIds.push(lastBeamId + 1 + k);
  lines.push(``);

  // Area connectivities (sólo si hay slab)
  if (hasSlab) {
    lines.push(`$ AREA CONNECTIVITIES`);
    let aid = 0;
    for (let j = 0; j < ny; j++) {
      for (let i = 0; i < nx; i++) {
        aid++;
        const p1 = j*nNx + i + 1;
        const p2 = p1 + 1;
        const p3 = (j+1)*nNx + i + 2;
        const p4 = (j+1)*nNx + i + 1;
        lines.push(`  AREA "F${aid}"  FLOOR  4  "${p1}"  "${p2}"  "${p3}"  "${p4}"  0  0  0  0  `);
      }
    }
    lines.push(``);
  }

  // Point assigns: diaph + restraints + asignación story (CRITICAL para POINTLOAD)
  // ETABS necesita que cada punto plano esté POINTASSIGNado a un Level para que
  // las POINTLOAD se apliquen correctamente. Con slab → DIAPH. Sin slab → solo
  // asignación de story (sin DIAPH).
  lines.push(`$ POINT ASSIGNS`);
  for (let i = 1; i <= nNx * (ny + 1); i++) {
    if (hasSlab) {
      lines.push(`  POINTASSIGN  "${i}"  "Level_1"  DIAPH "D1"  `);
    } else {
      lines.push(`  POINTASSIGN  "${i}"  "Level_1"  `);
    }
  }
  for (const cp of cornerPids) {
    // EMPOTRAMIENTO COMPLETO: UX UY UZ RX RY RZ
    lines.push(`  POINTASSIGN  "${cp}"  "Base"  RESTRAINT "UX UY UZ RX RY RZ"  `);
  }
  lines.push(``);

  // Line assigns
  lines.push(`$ LINE ASSIGNS`);
  // Beams (E1..E16) → W360X60
  for (let i = 1; i <= beamPairs.length; i++) {
    lines.push(`  LINEASSIGN  "E${i}"  "Level_1"  SECTION "W360X60"  MINNUMSTA 3 AUTOMESH "YES"  MESHATINTERSECTIONS "YES"  `);
  }
  // Columns (E17..E20) → CFT_HSS250x10 (Filled Steel Tube — ETABS hace la
  // transformación compuesta internamente, no necesita property modifiers)
  for (const eId of colIds) {
    lines.push(`  LINEASSIGN  "E${eId}"  "Level_1"  SECTION "CFT_HSS250x10"  MINNUMSTA 3 AUTOMESH "YES"  MESHATINTERSECTIONS "YES"  `);
  }
  lines.push(``);

  // Area assigns (sólo si hay slab)
  if (hasSlab) {
    lines.push(`$ AREA ASSIGNS`);
    let aid = 0;
    for (let j = 0; j < ny; j++) {
      for (let i = 0; i < nx; i++) {
        aid++;
        lines.push(`  AREAASSIGN  "F${aid}"  "Level_1"  SECTION "Losa"  DIAPH  "D1"  OBJMESHTYPE "DEFAULT"  ADDRESTRAINT "Yes"  CARDINALPOINT "TOP"  TRANSFORMSTIFFNESSFOROFFSETS "No"  `);
      }
    }
    lines.push(``);
  }

  // Load patterns
  lines.push(`$ LOAD PATTERNS`);
  lines.push(`  LOADPATTERN "Dead"  TYPE  "Dead"  SELFWEIGHT  0`);
  lines.push(`  LOADPATTERN "Live"  TYPE  "Live"  SELFWEIGHT  0`);
  lines.push(``);

  // Loads
  if (hasSlab) {
    lines.push(`$ POINT OBJECT LOADS`);
    lines.push(``);
    lines.push(`$ SHELL OBJECT LOADS`);
    let aid = 0;
    for (let j = 0; j < ny; j++) {
      for (let i = 0; i < nx; i++) {
        aid++;
        lines.push(`  AREALOAD  "F${aid}"  "Level_1"  TYPE "UNIFF"  DIR "GRAV"  LC "Dead"  FVAL ${q_unif} `);
      }
    }
    lines.push(``);
  } else {
    // 4 puntos de 20 kN en midspan de cada viga perimetral
    // Bottom mid: (nx/2, 0) → pid = nx/2 + 1 = 3
    // Top mid: (nx/2, ny) → pid = ny*nNx + nx/2 + 1 = 23
    // Left mid: (0, ny/2) → pid = (ny/2)*nNx + 1 = 11
    // Right mid: (nx, ny/2) → pid = (ny/2)*nNx + nx + 1 = 15
    const midPids = [
      Math.floor(nx/2) + 1,
      ny * nNx + Math.floor(nx/2) + 1,
      Math.floor(ny/2) * nNx + 1,
      Math.floor(ny/2) * nNx + nx + 1,
    ];
    lines.push(`$ POINT OBJECT LOADS`);
    for (const pid of midPids) {
      // Sintaxis ETABS completa con todos los componentes (FX..MZ) en una línea.
      // ETABS rechaza POINTLOAD parcial cuando el modelo tiene punto borrado.
      lines.push(`  POINTLOAD  "${pid}"  "Level_1"  LC "Dead"  TYPE "FORCE"  FX 0 FY 0 FZ -${P_point} MX 0 MY 0 MZ 0`);
    }
    lines.push(``);
  }

  // Analysis options + mass + load cases
  lines.push(`$ ANALYSIS OPTIONS`);
  lines.push(`  ACTIVEDOF "UX UY UZ RX RY RZ"`);
  lines.push(`  PDELTA  METHOD "NONE"`);
  lines.push(`  AUTOMESHOPTIONS  MESHTYPE  "GENERAL"  FLOORMESHMAXSIZE  1.0 WALLMESHMAXSIZE  1.0`);
  lines.push(``);
  lines.push(`$ MASS SOURCE`);
  lines.push(`  MASSSOURCE  "MsSrc1"    INCLUDEELEMENTS "Yes"    INCLUDEADDEDMASS "No"    INCLUDELOADS "No"    ISDEFAULT "Yes"`);
  lines.push(``);
  lines.push(`$ LOAD CASES`);
  lines.push(`  LOADCASE "Dead"  TYPE  "Linear Static"  INITCOND  "PRESET"`);
  lines.push(`  LOADCASE "Dead"  LOADPAT  "Dead"  SF  1`);
  lines.push(`  LOADCASE "Live"  TYPE  "Linear Static"  INITCOND  "PRESET"`);
  lines.push(`  LOADCASE "Live"  LOADPAT  "Live"  SF  1`);
  lines.push(``);
  lines.push(`  END`);
  lines.push(`$ END OF MODEL FILE`);

  return lines.join("\r\n");
}

// ── Main ─────────────────────────────────────────────────────────────────
const SETUPS = ["cftNoSlab", "cftDeckSlab"];
const arg = process.argv[2];
const todo = arg ? [arg] : SETUPS;

const outDir = join(__dirname, "etabs");
if (!existsSync(outDir)) mkdirSync(outDir);

console.log("=== Generador .e2k del bench CFT ===");
console.log(`# CFT transformed-section properties (SHAPE General):`);
console.log(`#   A_cft = ${A_cft.toExponential(4)} m²   I_cft = ${I_cft.toExponential(4)} m⁴   J_cft = ${J_cft.toExponential(4)} m⁴`);
console.log("");

for (const s of todo) {
  if (!SETUPS.includes(s)) {
    console.error(`Setup desconocido: ${s}. Válidos: ${SETUPS.join(", ")}`);
    process.exit(1);
  }
  const txt = generateE2k(s);
  const outPath = join(outDir, `composite_cft_${s}.e2k`);
  writeFileSync(outPath, txt, "utf8");
  console.log(`[OK] ${outPath}  (${txt.split("\n").length} líneas)`);
}
